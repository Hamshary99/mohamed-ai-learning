"""
src/graph/state.py
Centralized State Schema for StudentGator Agentic RAG
"""

from typing import Annotated, List, Literal, Optional
from typing_extensions import TypedDict
from langchain_core.messages import BaseMessage
from langchain_core.documents import Document
from langgraph.graph.message import add_messages


class AgentState(TypedDict):
    """
    Centralized state schema passed between all nodes in the LangGraph workflow.
    Acts as a shared whiteboard: each node reads the data it needs and returns
    partial dictionary updates to advance the workflow.
    """

    # 1. Multi-Turn Conversation History (The Memory Buffer)
    # By default, returning a field from a node overwrites its value.
    # Annotated[..., add_messages] is a Reducer: it appends new messages
    # (HumanMessage, AIMessage, ToolMessage) to the existing list, allowing
    # follow-up questions across multi-turn chats without losing context.
    messages: Annotated[List[BaseMessage], add_messages]

    # 2. Extracted User Question for Current Turn
    # The active question extracted from the latest message in `messages`.
    # Keeps raw query text easily accessible for embeddings and BM25 searches.
    current_query: str

    # 3. Intent Classification Flag (Routing Decision)
    # Populated by the classifier node before retrieval.
    # Prevents triggering expensive Vector DB search and PDF retrieval for greetings or off-topic queries.
    # - "greeting": Student said "Hi" -> routes to fast greeting reply.
    # - "out_of_scope": Student asked off-topic questions (e.g. recipes, coding) -> routes to polite scope boundary reply.
    # - "institutional_rag": Student asked about visas/admission -> routes to RAG.
    intent: Optional[Literal["greeting", "out_of_scope", "institutional_rag"]]

    # 4. Domain / Jurisdiction Metadata Pre-Filter
    # Optional category (e.g. "eu_germany_admissions", "us_federal_immigration")
    # passed to ChromaDB pre-filtering to prevent cross-country policy leaks.
    category_filter: Optional[str]

    # 5. Retrieved Evidence Chunks (Search Results)
    # Populated by the retrieval node with top re-ranked chunks from the PDFs.
    # The generator node reads this to ground its answer and cite sources.
    retrieved_docs: List[Document]

    # 6. Final Generated Answer
    # The grounded response text generated by the model.
    # Consumed by the FastAPI streaming endpoint to return the response to the student.
    final_response: str
